package main

import (
	"context"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"os/signal"
	"path/filepath"
	"syscall"
	"time"

	"github.com/chad/graft/internal/drafter"
	"github.com/chad/graft/internal/evidence"
	"github.com/chad/graft/internal/lang"
	"github.com/chad/graft/internal/model"
	"github.com/chad/graft/internal/pipeline"
	"github.com/chad/graft/internal/recording"
	"github.com/chad/graft/internal/render"
)

const runUsage = `usage: graft run --config graft.json --spec SPEC.md --repo DIR --root DIR --accept

Drafts the spec, accepts the drafts as provenance records in --repo (--accept
is the human saying yes; without it nothing is written), then converges one
region per record into --root, in spec order. Each region is generated by the
model command in the config and lands only if the gates pass and the tier is
satisfied. Regions already current for their record are left alone.

exit codes:
  0  every region applied
  1  a region did not converge within its attempts (later regions not tried)
  2  refused before generating: usage, config, drafts needing a human decision,
     or --accept not given
  3  failed during generation (model command, gate or I/O error)
`

func runCmd(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("run", flag.ContinueOnError)
	fs.SetOutput(stderr)
	fs.Usage = func() { fmt.Fprint(stderr, runUsage); fs.PrintDefaults() }
	cfgPath := fs.String("config", "graft.json", "policy, gates, model, conventions")
	specPath := fs.String("spec", "", "markdown spec")
	repo := fs.String("repo", "", "provenance repo for the accepted records")
	root := fs.String("root", "", "code tree to generate into")
	accept := fs.Bool("accept", false, "accept the drafts as records (the human step)")
	renderOn := fs.Bool("render", false, "sedum lays out the skeleton; the model converges only the Body helpers")
	skelPath := fs.String("skeleton", "", "skeleton JSON for --render (default: graft.json \"skeleton\", else skeleton.json beside it)")
	samples := fs.Int("samples", 1, "model answers drawn per attempt; every one is checked and the smallest-diff passing one is applied (best-of-N)")
	logPath := fs.String("log", "", "evidence log (default <repo>/.graft/evidence.jsonl)")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if *specPath == "" || *repo == "" || *root == "" || fs.NArg() != 0 {
		fmt.Fprint(stderr, runUsage)
		return 2
	}
	if !*renderOn && *skelPath != "" {
		fmt.Fprintln(stderr, "graft: --skeleton has no effect without --render")
		return 2
	}
	if *samples < 1 {
		fmt.Fprintln(stderr, "graft: --samples must be at least 1")
		return 2
	}
	cfg, gates, err := loadConvergeConfig(*cfgPath)
	if err != nil {
		fmt.Fprintf(stderr, "graft: %v\n", err)
		return 2
	}
	if cfg.Model == nil || len(cfg.Model.Argv) == 0 || cfg.Tier == "" || cfg.Conventions == "" {
		fmt.Fprintln(stderr, "graft: graft run needs model.argv, tier and conventions in the config")
		return 2
	}
	if _, ok := cfg.Policy[cfg.Tier]; !ok {
		fmt.Fprintf(stderr, "graft: unknown tier %q\n", cfg.Tier)
		return 2
	}
	conv, err := os.ReadFile(filepath.Join(filepath.Dir(*cfgPath), cfg.Conventions))
	if err != nil {
		fmt.Fprintf(stderr, "graft: conventions: %v\n", err)
		return 2
	}
	visible, err := loadVisible(*cfgPath, cfg)
	if err != nil {
		fmt.Fprintf(stderr, "graft: %v\n", err)
		return 2
	}
	profile, err := lang.Resolve(cfg.Language)
	if err != nil {
		fmt.Fprintf(stderr, "graft: %v\n", err)
		return 2
	}
	spec, err := os.ReadFile(*specPath)
	if err != nil {
		fmt.Fprintf(stderr, "graft: %v\n", err)
		return 2
	}
	drafts := drafter.Drafts(string(spec))
	if *renderOn && len(cfg.Files) > 0 {
		fmt.Fprintln(stderr, "graft: config \"files\" has no effect with --render (the skeleton places files); remove it")
		return 2
	}
	opts := pipeline.AcceptOptions{Ext: profile.Ext, Files: cfg.Files}
	// Bad keys and paths show on a dry run too, not only with --accept.
	if err := opts.CheckConfigured(drafts); err != nil {
		fmt.Fprintf(stderr, "graft: %v\n", err)
		return 2
	}
	if !*accept {
		for _, p := range drafter.Map(drafts, nil) {
			fmt.Fprintf(stdout, "%s — %s\n", p.Draft.Section, p.Kind)
		}
		fmt.Fprintln(stderr, "graft: nothing written; review the drafts above and re-run with --accept")
		return 2
	}
	if !*renderOn {
		opts.Root = *root // plain mode: a new section never takes over an existing file
	}
	acc, err := pipeline.AcceptWith(*repo, drafts, "graft run", time.Now(), opts)
	if err != nil {
		fmt.Fprintf(stderr, "graft: %v\n", err)
		return 2
	}
	var skel *recording.Skeleton
	var sedum render.Sedum
	var gens string
	if *renderOn {
		sp := *skelPath
		if sp == "" {
			sp = cfg.Skeleton
			if sp == "" {
				sp = "skeleton.json"
			}
			sp = filepath.Join(filepath.Dir(*cfgPath), sp)
		}
		sb, err := os.ReadFile(sp)
		if err != nil {
			fmt.Fprintf(stderr, "graft: skeleton: %v\n", err)
			return 2
		}
		sk, err := recording.LoadSkeleton(sb)
		if err != nil {
			fmt.Fprintf(stderr, "graft: skeleton %s: %v\n", sp, err)
			return 2
		}
		skel = &sk
		bin, err := exec.LookPath("sedum")
		if err != nil {
			fmt.Fprintln(stderr, "graft: --render needs sedum on PATH")
			return 2
		}
		sedum = render.Exec(bin)
		gens = os.Getenv("SEDUM_GENERATORS")
		if gens == "" {
			home, _ := os.UserHomeDir()
			gens = filepath.Join(home, "sedum", "generators")
		}
		if _, err := os.Stat(gens); err != nil {
			fmt.Fprintf(stderr, "graft: sedum generators: %v (set SEDUM_GENERATORS)\n", err)
			return 2
		}
	}
	lp := *logPath
	if lp == "" {
		lp = filepath.Join(*repo, ".graft", "evidence.jsonl")
	}
	if err := os.MkdirAll(filepath.Dir(lp), 0o755); err != nil {
		fmt.Fprintf(stderr, "graft: %v\n", err)
		return 2
	}
	log, err := evidence.Open(lp)
	if err != nil {
		fmt.Fprintf(stderr, "graft: %v\n", err)
		return 2
	}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	out, err := pipeline.Run(ctx, pipeline.Config{
		Repo: *repo, Root: *root, Module: cfg.Module, Spec: string(spec), Conventions: string(conv), Visible: visible,
		Tier: cfg.Tier, Attempts: cfg.Attempts,
		Model: model.Command{Argv: cfg.Model.Argv, Timeout: time.Duration(cfg.Model.TimeoutSec) * time.Second},
		Gates: gates, Policy: evidence.Policy(cfg.Policy), Log: log, Progress: stdout,
		Skeleton: skel, Sedum: sedum, Generators: gens, Samples: *samples, Lang: profile,
	}, acc)
	applied, calls := 0, 0
	for _, o := range out {
		if o.Applied {
			applied++
		}
		calls += o.Calls
	}
	if *samples > 1 {
		fmt.Fprintf(stdout, "%d model calls (samples %d)\n", calls, *samples)
	}
	fmt.Fprintf(stdout, "%d/%d regions applied (guarantee: checked)\n", applied, len(acc))
	if err != nil {
		fmt.Fprintf(stderr, "graft: %v\n", err)
		if len(out) > 0 && !out[len(out)-1].Applied {
			return 1
		}
		return 3
	}
	return 0
}
